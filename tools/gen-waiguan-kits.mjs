#!/usr/bin/env node
// tools/gen-waiguan-kits.mjs — (re)write server/sim/content/kits/waiguan/index.js from the kit files next to it.
//
// Every `server/sim/content/kits/waiguan/char_*.js` (one 外援 operator, `export default (bb, chess, def) => Kit`) is
// imported statically and registered for BOTH chess ids of its operator (chess_char_diy_5_<charId>_a and
// chess_char_diy_6_<charId>_a; the elite `_b` defs resolve through their baseId). The file name IS the charId and must
// be one of data/waiguan.json `candidates`.
//
// Usage: node tools/gen-waiguan-kits.mjs [--check] [--dir <kits dir>]
//   --check   write nothing; exit 1 when index.js is not what this script would write (CI / tests)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const di = args.indexOf('--dir');
const DIR = di >= 0 ? path.resolve(args[di + 1]) : path.join(ROOT, 'server/sim/content/kits/waiguan');
const roster = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/waiguan.json'), 'utf8'));
const known = new Set((roster.candidates || []).map((c) => c.charId));

const files = fs.readdirSync(DIR).filter((f) => /^char_[A-Za-z0-9_]+\.js$/.test(f)).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
const bad = files.map((f) => f.slice(0, -3)).filter((id) => !known.has(id));
if (bad.length) { console.error(`not a 外援 candidate: ${bad.join(', ')}`); process.exit(2); }

const ident = (charId) => charId.replace(/[^A-Za-z0-9_$]/g, '_');
const lines = [
  '// server/sim/content/kits/waiguan/index.js — GENERATED by tools/gen-waiguan-kits.mjs: do not edit by hand.',
  '// Every 外援 / 甄选 kit file (waiguan/char_*.js, `export default (bb, chess, def) => Kit`) registered for BOTH of its',
  '// chess ids — chess_char_diy_5_<charId>_a and chess_char_diy_6_<charId>_a (elites `_b` resolve through their baseId).',
  '// Static imports only: the Worker / replay-engine bundle (tools/build-worker.mjs) cannot follow a computed import().',
  '',
  ...files.map((f) => `import ${ident(f.slice(0, -3))} from './${f}';`),
  '',
  '/** [charId, kit] in charId order. */',
  'export const WAIGUAN_KITS = Object.freeze([',
  ...files.map((f) => `  ['${f.slice(0, -3)}', ${ident(f.slice(0, -3))}],`),
  ']);',
  '',
  'const out = {};',
  'for (const [charId, kit] of WAIGUAN_KITS) {',
  '  out[`chess_char_diy_5_${charId}_a`] = kit;',
  '  out[`chess_char_diy_6_${charId}_a`] = kit;',
  '}',
  'export default Object.freeze(out);',
  '',
];
const text = lines.join('\n');
const target = path.join(DIR, 'index.js');
const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
if (check) {
  if (cur !== text) { console.error(`${path.relative(ROOT, target)} is stale: run node tools/gen-waiguan-kits.mjs`); process.exit(1); }
  console.log(`index up to date (${files.length} kits)`);
} else {
  if (cur !== text) fs.writeFileSync(target, text);
  console.log(`${files.length} 外援 kits registered (${files.length * 2} chess ids)`);
}
